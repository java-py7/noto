export const DEFAULT_THEME_ID = 'default';

/**
 * Returns theme definition by ID, falling back to default
 */
export function getTheme(themeId) {
  return THEMES.find((t) => t.id === themeId) || THEMES[0];
}

/**
 * Applies the given theme ID to the document root immediately
 */
export function applyTheme(themeId) {
  const theme = getTheme(themeId);
  const root = document.documentElement;

  // Apply data-theme attribute
  root.setAttribute('data-theme', theme.id);

  // Apply all CSS variables directly to the root element
  Object.entries(theme.cssVars).forEach(([key, val]) => {
    root.style.setProperty(key, val);
  });

  // Save to persistent localStorage
  localStorage.setItem('noto_theme', theme.id);

  return theme;
}
